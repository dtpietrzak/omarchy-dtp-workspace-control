const assert = require("assert")
const keys = require("../TextKeys.js")

assert.strictEqual(keys.opFor("", "a", false, false), "insert")
assert.strictEqual(keys.opFor("", "É", false, false), "insert")
assert.strictEqual(keys.opFor("", "\r", false, false), "")
assert.strictEqual(keys.opFor("", "", false, false), "")
assert.strictEqual(keys.opFor("", "a", false, true), "")
assert.strictEqual(keys.opFor("backspace", "\b", false, false), "deleteBack")
assert.strictEqual(keys.opFor("backspace", "\b", true, false), "deleteWordBack")
assert.strictEqual(keys.opFor("delete", "\u007f", false, false), "deleteForward")
assert.strictEqual(keys.opFor("v", "\u0016", true, false), "paste")
assert.strictEqual(keys.opFor("x", "\u0018", true, false), "cut")
assert.strictEqual(keys.opFor("u", "\u0015", true, false), "clear")
// Ctrl+A and Ctrl+C stay with the TextInput.
assert.strictEqual(keys.opFor("", "\u0001", true, false), "")
assert.strictEqual(keys.opFor("", "\u0003", true, false), "")

assert.deepStrictEqual(keys.apply("fire", 2, 2, "insert", "X"), { text: "fiXre", cursor: 3 })
assert.deepStrictEqual(keys.apply("firefox", 1, 4, "insert", "o"), { text: "fofox", cursor: 2 })
assert.deepStrictEqual(keys.apply("firefox", 4, 1, "insert", "o"), { text: "fofox", cursor: 2 })
assert.deepStrictEqual(keys.apply("fire", 0, 0, "deleteBack"), { text: "fire", cursor: 0 })
assert.deepStrictEqual(keys.apply("fire", 4, 4, "deleteBack"), { text: "fir", cursor: 3 })
assert.deepStrictEqual(keys.apply("fire", 1, 3, "deleteBack"), { text: "fe", cursor: 1 })
assert.deepStrictEqual(keys.apply("fire", 4, 4, "deleteForward"), { text: "fire", cursor: 4 })
assert.deepStrictEqual(keys.apply("fire", 0, 0, "deleteForward"), { text: "ire", cursor: 0 })
assert.deepStrictEqual(keys.apply("a😀", 3, 3, "deleteBack"), { text: "a", cursor: 1 })
assert.deepStrictEqual(keys.apply("😀a", 0, 0, "deleteForward"), { text: "a", cursor: 0 })
assert.deepStrictEqual(keys.apply("open fire fox", 13, 13, "deleteWordBack"), { text: "open fire ", cursor: 10 })
assert.deepStrictEqual(keys.apply("open fire ", 10, 10, "deleteWordBack"), { text: "open ", cursor: 5 })
assert.deepStrictEqual(keys.apply("open fire", 4, 4, "deleteWordForward"), { text: "open", cursor: 4 })
assert.deepStrictEqual(keys.apply("firefox", 4, 7, "cut"), { text: "fire", cursor: 4 })
assert.deepStrictEqual(keys.apply("firefox", 3, 3, "clear"), { text: "", cursor: 0 })
assert.deepStrictEqual(keys.apply("fire", 99, 99, "insert", "!"), { text: "fire!", cursor: 5 })

assert.strictEqual(keys.cleanPaste("  fire\nfox\r\n"), "fire fox")
assert.strictEqual(keys.cleanPaste("a\u0000b\u001bc�"), "abc")
assert.strictEqual(keys.cleanPaste(null), "")
assert.strictEqual(keys.cleanPaste("x".repeat(5000)).length, keys.PASTE_LIMIT)
assert.strictEqual(keys.PASTE_LIMIT, 128)
assert.strictEqual(Array.from(keys.cleanPaste("😀".repeat(200))).length, 128)

console.log("textkeys ok")
